/// The research notebook's own 120-day synthetic trace, at the hourly resolution this app's
/// grid works in.
///
/// ## Why this fixture exists
///
/// The unit tests around it check that each piece of the pipeline does what it says. This one
/// checks the only thing that actually matters: that the whole arrangement, ported to Swift and
/// rebuilt on the app's own hourly grid and the app's own types, still finds the signal the
/// notebook found. A port can pass every component test and still lose the result — a window
/// boundary off by an hour, a day mean taken over the wrong set, a label attached to the
/// neighbouring window.
///
/// ## What it is
///
/// `barosense_synthetic_120d_15min.csv` from the research repository, resampled to hourly means
/// (2880 readings from 2025-03-03), plus the 90 self-reports it
/// contains. Hourly rather than quarter-hourly because that is the grid `RiskPressureGrid`
/// builds — the bucketing from raw readings is `HourlyPressureGrid`'s own tested job, and
/// feeding it back through here would test it twice and this once.
///
/// **Synthetic, and generated with an explicit barometric effect written into it.** Numbers
/// measured on it are a ceiling. See `WellbeingRiskPrior` for what that does and does not
