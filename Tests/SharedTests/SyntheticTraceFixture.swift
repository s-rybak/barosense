    /// The 1–10 intensity recorded with each. Present so the fixture carries the whole row;
    /// this model's label is the **occurrence** of an entry, not its intensity.
    static let checkInIntensities: [Int] = parse(intensityCSV).map { Int($0) }

    /// An arbitrary but fixed instant, so every run of the test sees the same calendar.
    /// UTC noon on the first day, which keeps the trace's own local hours intact.
