    /// Readings as the app stores them.
    static func samples() -> [PressureSample] {
        pressureHPa.enumerated().map { index, value in
            PressureSample(id: UUID(),
                           timestamp: start.addingTimeInterval(TimeInterval(index) * 3600),
                           pressure: Pressure(hectopascals: value))
        }
    }

    /// Self-reports as the app stores them.
    static func checkIns() -> [CheckIn] {
        checkInOffsets.enumerated().map { index, offset in
            CheckIn(id: UUID(),
                    timestamp: start.addingTimeInterval(offset),
                    intensity: CheckInIntensity(clamping: checkInIntensities[index]),
                    tagIDs: [],
                    medications: [],
                    health: nil,
                    note: nil)
        }
    }

    /// The instant a run is taken "as of": one hour past the last reading.
    static var now: Date {
        start.addingTimeInterval(TimeInterval(pressureHPa.count) * 3600)
    }

